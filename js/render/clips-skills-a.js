// 옆으로 가는 기술 묶음. 오른쪽(+x)으로 가는 쪽만 적고 왼쪽은 mirror 로 얻는다. 적는 법은 clip-tools.js 의 bake 에 있다.
// 기술마다 공이 가는 쪽에 있을 때의 것과 먼 쪽에 있을 때의 것(.far) 두 벌이다
import { move, land, both, still, ahead, stay, gone, B, edge, outside, inside, sole, toe } from './clip-tools.js';

// 볼롤: 왼발바닥을 공 위에 얹고 몸 앞을 가로질러 가는 쪽으로 굴린다. 뒤에서 보면 왼다리가 오른다리 앞으로 엇갈린다.
// 가는 쪽에 있던 공은 몸이 지나쳐 왼쪽에 올 때까지 두었다가 굴린다
function ballRoll(far) {
  const dur = 0.6, press = sole(-0.2), d = far ? 0 : 0.07, on = far ? 0.035 : 0.115, off = far ? 0.155 : 0.195;
  const b0 = still(far, on, -0.44), b1 = B(far ? 0.22 : 0.4, -0.38);
  return move(dur, [
    { t: 0, L: [far ? -0.45 : -0.15, 0.2, far ? -0.3 : 0.2, -0.3], R: [far ? 0.2 : 0.25, 0, -0.05], ball: still(far, 0, -0.6) },
    { t: on, L: press, ball: b0, carry: true },
    // 윗몸은 세운 채 골반만 가는 쪽으로 틀고 어깨는 남긴다. 왼팔은 뒤 바깥으로 뻗고 오른팔은 접어 앞으로 낸다. 눈은 발밑의 공에 있다
    { t: 0.07 + d, root: { y: -0.09, x: -0.05, lean: -0.06, yaw: -0.25 }, hips: [0.05, -0.2, 0], spine: [-0.14, 0.4, 0], head: [-0.05, 0.05, 0],
      shL: [-0.6, 0, -1.0], elL: [0.6, 0, 0], shR: [0.6, 0, 0.5], elR: [1.4, 0, 0] },
    { t: 0.088, R: stay(-0.5) },
    // 디딘 발이 살짝 뛰어 굴리는 다리 뒤로 따라간다. 발바닥은 공을 누른 채 몸 앞을 다 건너간다
    { t: 0.13 + d, root: { y: -0.03, x: 0, yaw: -0.38 }, R: [0.02, 0.14, 0.18, -0.7] },
    { t: off, L: press, ball: b1, carry: true },
    // 발을 공 뒤에 딛고 한 번 민다. 공은 굴리던 쪽으로 계속 굴러가고 고개가 올라온다
    { t: off + 0.008, L: [b1.x + 0.05, 0.3, -0.1, 0, -0.2] },
    { t: off + 0.022, root: { lean: -0.14, yaw: -0.3 }, spine: [-0.25, 0.1, 0.05], head: [0.22, -0.1, 0], shL: [0.3, 0, -0.7], elL: [1.2, 0, 0], shR: [-0.4, 0, 0.9], elR: [0.7, 0, 0],
      L: [b1.x, 0, 0.05, 0, -0.2] },
    { t: off + 0.048, L: stay(-0.5) },
    { t: 0.3 + d, ease: 'out', ball: ahead(far) },
    ...land(dur, far, far ? 0.21 : 0.25),
  ], far);
}

// 발바닥 드리블: 발바닥으로 공을 몸 쪽으로 끌어당겼다가 그대로 가는 쪽으로 끈다.
