// V자 드리블: 발바닥으로 공을 몸 쪽으로 끌어당겼다가, 같은 발 안쪽으로 앞으로 밀어 낸다.
// 가는 쪽의 공은 오른발로 끌어 골반을 열며 밀고, 먼 쪽의 공은 왼발로 끌어 몸 앞으로 밀어 준다
